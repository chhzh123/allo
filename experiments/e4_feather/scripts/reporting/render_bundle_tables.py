#!/usr/bin/env python3
"""Render the results bundle's tables and JSON from `results.csv` alone.

    render_bundle_tables.py <results.csv> <bundle dir>

This replaces the table half of `e4_collect.py` / `e4b_collect.py`, which built
the bundle from run directories on the machine **and from a hard-coded list of
run ids**. That list is why the bundle went stale twice: rows whose id was not
in it -- the row-wise loader's, then the re-measured conv ones -- were dropped
without a word, and the file kept claiming `results.csv` was its source.

Here the CSV is the source in fact. Rows are grouped by what is in them rather
than looked up by name, and the footer states how many rows landed in each
table and how many landed in neither, so a row can no longer go missing
quietly.
"""

import csv
import json
import os
import sys


def num(v, places=0):
    if v in (None, "", "None"):
        return ""
    try:
        f = float(v)
    except ValueError:
        return str(v)
    return f"{f:,.{places}f}" if places else f"{int(round(f)):,}"


def side(row):
    """Which system a row is, short enough for a table cell."""
    v, s = row["variant"], row["system"]
    if s.startswith("SPMW"):
        return "SPMW " + ("resident" if "resident" in v or "single tile" in v else "streamed")
    for tag, label in (
        ("row-wise weight loader", "RTL row loader"),
        ("corrected controller", "RTL corrected"),
        ("shipped controller", "RTL shipped"),
    ):
        if tag in v:
            return label
    return s


def family(row):
    w = row["workload"]
    if w.startswith("conv"):
        return "conv 16x16x64 -> 64ch 3x3"
    if w.startswith("gemm M=N=K=128") or "gemm128" in row["run_id"]:
        return "GEMM 128^3"
    if "single tile" in w or "single_tiles" in row["run_id"]:
        return "single tiles"
    return w.split(",")[0][:40]


def operands(row):
    """general or constrained -- otherwise two rows that differ only in the
    stimulus look like the same row printed twice, which they did."""
    w = row["weight_mode"]
    return "constrained" if w.startswith("constrained") else "general"


def mode(row):
    w = row["workload"]
    if "MODE 1" in w or "resident" in row["run_id"]:
        return "weights resident"
    if "MODE 0" in w or "feed" in row["run_id"]:
        return "a feed per tile"
    return ""


def main():
    results, bundle = sys.argv[1], sys.argv[2]
    rows = list(csv.DictReader(open(results, encoding="utf-8")))

    cyc = [r for r in rows if r.get("completion_cycles")]
    pnr = [r for r in rows if r.get("lut")]
    rest = [r for r in rows if r not in cyc and r not in pnr]

    out = [
        "# E4 tables, rendered from `results.csv`",
        "",
        "Generated by `experiments/e4_feather/scripts/reporting/"
        "render_bundle_tables.py`, which reads the CSV beside this file and"
        " nothing else.",
        "",
        "### Cycles",
        "",
        "| workload | N | system | mode | operands | tiles | first tile | completion | cycles/tile | status |",
        "|---|---:|---|---|---|---:|---:|---:|---:|---|",
    ]
    for r in sorted(cyc, key=lambda r: (family(r), int(r["array_size"].split("x")[0]), side(r), mode(r), operands(r))):
        out.append(
            f"| {family(r)} | {r['array_size'].split('x')[0]} | {side(r)} | {mode(r)} | {operands(r)} "
            f"| {num(r['tiles'])} | {num(r['first_output_cycles'])} "
            f"| {num(r['completion_cycles'])} | {num(r['cycles_per_tile'], 1)} | {r['status']} |"
        )

    out += [
        "",
        "### Place-and-route, xcu280-fsvh2892-2L-e, Vivado 2023.2, 3.333 ns",
        "",
        "| design | N | status | LUT | FF | DSP | BRAM18 | URAM | WNS ns | unrouted |",
        "|---|---:|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in sorted(pnr, key=lambda r: (int(r["array_size"].split("x")[0]), side(r))):
        out.append(
            f"| {side(r)} | {r['array_size'].split('x')[0]} | {r['status']} | {num(r['lut'])} "
            f"| {num(r['ff'])} | {num(r['dsp'])} | {num(r['bram_18k_equiv'])} | {num(r['uram'])} "
            f"| {num(r['wns_ns'], 3)} | {num(r['unrouted'])} |"
        )

    out += ["", "### Coverage", ""]
    out.append(f"{len(rows)} rows in `results.csv`: {len(cyc)} with cycles, {len(pnr)} routed, "
               f"{len(rest)} in neither table.")
    if rest:
        out.append("")
        out.append("Rows in neither, named rather than dropped:")
        out.append("")
        for r in rest:
            out.append(f"- `{r['run_id']}` -- {r['status']}"
                       + (f": {r['failure_reason']}" if r.get("failure_reason") else ""))

    with open(os.path.join(bundle, "README_tables.md"), "w", encoding="utf-8") as h:
        h.write("\n".join(out) + "\n")
    with open(os.path.join(bundle, "results.json"), "w", encoding="utf-8") as h:
        json.dump(rows, h, indent=1, sort_keys=True)
    print(f"{len(rows)} rows -> {bundle}/README_tables.md and results.json "
          f"({len(cyc)} cycles, {len(pnr)} routed, {len(rest)} neither)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
