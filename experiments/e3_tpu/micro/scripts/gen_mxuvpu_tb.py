"""An xsim testbench for Gemmini's MxuVpu, driving the same streaming protocol.

`MxuVpuStream.scala` is the driver of record and it stays. This exists because
chiseltest has no verilator on this machine and falls back to a Scala
interpreter whose cost grows far faster than the mesh: 63 seconds at 4x4, and
E1 measured six hours for a 16x16.

It is a *check*, not a substitute: it reads the same stimulus file, implements
the same protocol, prints the same line, and is validated at S=4 against the
number chiseltest produced there. A fallback that has never agreed with the
thing it falls back from is not evidence.
"""

import argparse


def tb(dim, tiles, stim):
    j = range(dim)
    # Widths Chisel derives rather than declares: `total_rows` is
    # log2Up(block_size + 1) and `pe_control.shift` is log2Up(accType width).
    rows_w = max(1, (dim + 1 - 1).bit_length())
    return f"""// Generated by gen_mxuvpu_tb.py -- do not edit.
`timescale 1ns/1ps

module tb;
  localparam int DIM   = {dim};
  localparam int TILES = {tiles};
  localparam int TILE  = DIM * DIM;

  reg clk = 0;
  reg rst = 1;
  always #5 clk = ~clk;

  integer cyc = 0;
  always @(posedge clk) cyc <= cyc + 1;

  // -- the shared stimulus ----------------------------------------------------
  integer A [0:TILES*TILE-1];
  integer B [0:TILES*TILE-1];
  integer C [0:TILES*TILE-1];
  integer BIAS [0:DIM-1];
  integer SHIFT, NT, SS;

  integer fd, k, code;
  string tok;
  initial begin
    fd = $fopen("{stim}", "r");
    if (fd == 0) begin $display("MXUVPU_XSIM NO_STIMULUS"); $finish; end
    while (!$feof(fd)) begin
      code = $fscanf(fd, "%s", tok);
      if (code != 1) break;
      case (tok)
        "S":     code = $fscanf(fd, "%d", SS);
        "TILES": code = $fscanf(fd, "%d", NT);
        "SHIFT": code = $fscanf(fd, "%d", SHIFT);
        "SEED":  code = $fscanf(fd, "%d", k);
        "BIAS":  for (k = 0; k < DIM; k = k + 1) code = $fscanf(fd, "%d", BIAS[k]);
        "A":     for (k = 0; k < TILES*TILE; k = k + 1) code = $fscanf(fd, "%d", A[k]);
        "B":     for (k = 0; k < TILES*TILE; k = k + 1) code = $fscanf(fd, "%d", B[k]);
        "C":     for (k = 0; k < TILES*TILE; k = k + 1) code = $fscanf(fd, "%d", C[k]);
        default: ;
      endcase
    end
    $fclose(fd);
    if (SS != DIM || NT != TILES) begin
      $display("MXUVPU_XSIM STIMULUS_MISMATCH S=%0d TILES=%0d", SS, NT);
      $finish;
    end
  end

  // -- the device -------------------------------------------------------------
  reg         a_valid = 0, b_valid = 0, d_valid = 0, req_valid = 0;
  reg  signed [7:0] a_bits [0:DIM-1];
  reg  signed [7:0] b_bits [0:DIM-1];
  reg  signed [7:0] d_bits [0:DIM-1];
  reg  [31:0] scale;
  wire a_ready, b_ready, d_ready, req_ready, out_valid;
  wire signed [7:0] out_bits [0:DIM-1];

  MxuVpu dut (
    .clock(clk), .reset(rst),
    .io_a_ready(a_ready), .io_a_valid(a_valid),
{chr(10).join(f"    .io_a_bits_{i}_0(a_bits[{i}])," for i in j)}
    .io_b_ready(b_ready), .io_b_valid(b_valid),
{chr(10).join(f"    .io_b_bits_{i}_0(b_bits[{i}])," for i in j)}
    .io_d_ready(d_ready), .io_d_valid(d_valid),
{chr(10).join(f"    .io_d_bits_{i}_0(d_bits[{i}])," for i in j)}
    .io_req_ready(req_ready), .io_req_valid(req_valid),
    .io_req_bits_pe_control_dataflow(1'b1),
    .io_req_bits_pe_control_propagate(1'b1),
    .io_req_bits_pe_control_shift(5'd0),
    .io_req_bits_a_transpose(1'b0),
    .io_req_bits_bd_transpose(1'b0),
    .io_req_bits_total_rows({rows_w}'d{dim}),
    .io_req_bits_tag_id(8'd1),
    .io_req_bits_flush(2'd0),
    .io_scale(scale),
    .io_out_ready(1'b1), .io_out_valid(out_valid),
{chr(10).join(f"    .io_out_bits_data_{i}_0(out_bits[{i}])," for i in j)}
    .io_out_bits_acc_bank_id(), .io_out_bits_fromDMA()
  );

  // -- collecting the rows ----------------------------------------------------
  integer got [0:(TILES+1)*DIM-1][0:DIM-1];
  integer rows = 0;
  integer first_in = -1;
  integer last_out = -1;
  integer tile_done [0:TILES-1];
  integer i;

  always @(posedge clk) if (!rst) begin
    if (out_valid) begin
      if (rows < (TILES+1)*DIM) begin
        for (i = 0; i < DIM; i = i + 1) got[rows][i] = out_bits[i];
      end
      rows = rows + 1;
      last_out = cyc;
      // Pass 0 is the warm-up; after it, every DIM rows completes one tile.
      if (rows % DIM == 0 && rows / DIM >= 2 && rows / DIM - 2 < TILES)
        if (tile_done[rows/DIM - 2] < 0) tile_done[rows/DIM - 2] = cyc;
    end
    if ((a_valid && a_ready) && first_in < 0) first_in = cyc;
  end

  task automatic issue();
    integer guard;
    begin
      req_valid = 1;
      guard = 0;
      while (req_ready !== 1'b1 && guard < 100) begin @(posedge clk); guard = guard + 1; end
      @(posedge clk);
      req_valid = 0;
    end
  endtask

  // One pass: DIM rows of activations with the *next* tile's weights behind
  // them, bottom row first. -1 means "none": the warm-up has no activations
  // and the final pass has no weights to shift in.
  task automatic pass(input integer act, input integer wt);
    integer row, guard, c;
    begin
      row = 0; guard = 0;
      while (row < DIM && guard < 500) begin
        a_valid = 1; b_valid = 1; d_valid = 1;
        for (c = 0; c < DIM; c = c + 1) begin
          a_bits[c] = (act < 0) ? 8'sd0 : A[act*TILE + row*DIM + c];
          b_bits[c] = BIAS[c];
          d_bits[c] = (wt  < 0) ? 8'sd0 : B[wt*TILE + (DIM-1-row)*DIM + c];
        end
        @(posedge clk);
        if (a_ready === 1'b1) row = row + 1;
        guard = guard + 1;
      end
      a_valid = 0; b_valid = 0; d_valid = 0;
    end
  endtask

  integer t, r, cidx, wrong, first_bad, gaps, med;
  integer gap [0:TILES-2];
  integer tmp;
  initial begin
    for (t = 0; t < TILES; t = t + 1) tile_done[t] = -1;
    scale = SHIFT;
    repeat (8) @(posedge clk);
    rst = 0;
    @(posedge clk);

    issue(); pass(-1, 0);
    for (t = 0; t < TILES; t = t + 1) begin
      issue();
      pass(t, (t + 1 < TILES) ? t + 1 : -1);
    end
    for (t = 0; t < 400 && rows < (TILES+1)*DIM; t = t + 1) @(posedge clk);

    wrong = 0; first_bad = -1;
    for (t = 0; t < TILES; t = t + 1)
      for (r = 0; r < DIM; r = r + 1) begin
        cidx = (t + 1) * DIM + r;
        for (i = 0; i < DIM; i = i + 1)
          if (cidx >= rows || got[cidx][i] !== C[t*TILE + r*DIM + i]) begin
            if (first_bad < 0) first_bad = t * DIM + r;
            wrong = wrong + 1;
            i = DIM;
          end
      end

    gaps = 0;
    for (t = 1; t < TILES; t = t + 1)
      if (tile_done[t] > 0 && tile_done[t-1] > 0) begin
        gap[gaps] = tile_done[t] - tile_done[t-1];
        gaps = gaps + 1;
      end
    for (t = 0; t < gaps; t = t + 1)
      for (r = t + 1; r < gaps; r = r + 1)
        if (gap[r] < gap[t]) begin tmp = gap[t]; gap[t] = gap[r]; gap[r] = tmp; end
    med = (gaps > 0) ? gap[gaps/2] : -1;

    $display("MXUVPU_STREAM dim=%0d tiles=%0d shift=%0d correct=%s rows_out=%0d want_rows=%0d wrong_rows=%0d first_in=%0d last_out=%0d latency=%0d interval=%0d interval_min=%0d interval_max=%0d total=%0d",
      DIM, TILES, SHIFT,
      (wrong == 0 && rows == (TILES+1)*DIM) ? "true" : "false",
      rows, (TILES+1)*DIM, wrong, first_in+1, last_out+1,
      (tile_done[0] >= 0 && first_in >= 0) ? tile_done[0] - first_in + 1 : -1,
      med, (gaps > 0) ? gap[0] : -1, (gaps > 0) ? gap[gaps-1] : -1,
      (last_out >= 0 && first_in >= 0) ? last_out - first_in + 1 : -1);
    for (t = 0; t < TILES; t = t + 1)
      $display("MXUVPU_TILE t=%0d done=%0d", t, tile_done[t] + 1);
    if (wrong != 0) $display("  first wrong output row: %0d", first_bad);
    $finish;
  end
endmodule
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--size", type=int, required=True)
    parser.add_argument("--tiles", type=int, default=16)
    parser.add_argument("--stim", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write(tb(args.size, args.tiles, args.stim))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
