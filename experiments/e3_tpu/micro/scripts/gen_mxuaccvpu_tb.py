"""An xsim testbench for Gemmini's MxuAccVpu: a fixed workload on any mesh.

`gen_mxuvpu_tb.py` runs E3's microbenchmark with the tile sized to the mesh.
This runs the S=16 stimulus -- sixteen 16x16x16 tiles -- on a ``dim``-wide
mesh, which is what Gemmini's own tiling does with a large matmul: each tile
becomes ``(16/dim)^2`` weight blocks, a block's 16 rows go in ``16/dim``
requests of ``dim`` rows (``MeshWithDelaysReq.total_rows`` is at most the
mesh's side), and the ``16/dim`` partial sums of each output are added in
AccumulatorMem before the scale unit reads the group out.

The weight double buffer works as in E3: a request's ``propagate`` flips the
buffer, and the rows it streams load ``d`` into the one not in use. So the
first request of a block flips to that block's weights, the others keep them,
and the last carries the next block's weights; one warm-up request loads the
first. The bias rides the mesh's top-of-array input on a group's first K
block only.

**A request's tag labels the next request's rows.** Gemmini's output address
travels with the preload -- ``preload(B, C)`` then ``compute(A, D)`` -- and the
rows a request computes come out under the tag of the request before it. So
each request here carries the tag of the one after it, the warm-up carries
the first, and the last carries Gemmini's garbage tag.

Same stimulus file, same golden, same printed line as `gen_mxuvpu_tb.py`, so
`first_in`, `latency`, `interval` and `total` mean what they meant there.

Any tile shape runs: the stimulus header gives ``S`` (a square tile) or ``M``,
``K`` and ``N``, and a group -- one column block's ``M`` rows -- is what the
accumulator reads out, so `MXUACC_GROUPS` reports per group. LLaMA's slice
(`test_spmw_llama_ffn.dump_llama`) is one 64 x 2048 x 128 tile with no bias.
"""

import argparse


def shape_of(stim):
    """``(M, K, N, tiles)`` from a stimulus file's header lines."""
    keys = {}
    with open(stim, encoding="utf-8") as handle:
        for line in handle:
            key, _, rest = line.partition(" ")
            if key in ("S", "M", "K", "N", "TILES"):
                keys[key] = int(rest.split()[0])
    if "S" in keys:
        return keys["S"], keys["S"], keys["S"], keys["TILES"]
    return keys["M"], keys["K"], keys["N"], keys["TILES"]


def tb(dim, tiles, stim, m=16, k=16, n=16):
    j = range(dim)
    groups = tiles * (n // dim)  # (tile, column block) pairs, each read out once
    rows_w = max(1, dim.bit_length())
    return f"""// Generated by gen_mxuaccvpu_tb.py -- do not edit.
`timescale 1ns/1ps

module tb;
  localparam int DIM   = {dim};
  localparam int M     = {m};
  localparam int K     = {k};
  localparam int N     = {n};
  localparam int TILES = {tiles};
  localparam int KB    = K / DIM;
  localparam int NB    = N / DIM;
  localparam int SUBS  = M / DIM;         // requests a block's M rows take
  localparam int GROUPS = {groups};
  localparam int OUTR  = GROUPS * M;      // rows the scale unit emits

  reg clk = 0;
  reg rst = 1;
  always #5 clk = ~clk;

  integer cyc = 0;
  always @(posedge clk) cyc <= cyc + 1;

  // -- the shared stimulus ----------------------------------------------------
  integer A [0:TILES*M*K-1];
  integer B [0:TILES*K*N-1];
  integer C [0:TILES*M*N-1];
  integer BIAS [0:N-1];                   // no BIAS line: none, as LLaMA's
  integer SHIFT, NT, MM = -1, KK = -1, NN = -1;

  integer fd, k, code;
  string tok;
  initial begin
    for (k = 0; k < N; k = k + 1) BIAS[k] = 0;
    fd = $fopen("{stim}", "r");
    if (fd == 0) begin $display("MXUACC_XSIM NO_STIMULUS"); $finish; end
    while (!$feof(fd)) begin
      code = $fscanf(fd, "%s", tok);
      if (code != 1) break;
      case (tok)
        "S":     begin code = $fscanf(fd, "%d", MM); KK = MM; NN = MM; end
        "M":     code = $fscanf(fd, "%d", MM);
        "K":     code = $fscanf(fd, "%d", KK);
        "N":     code = $fscanf(fd, "%d", NN);
        "TILES": code = $fscanf(fd, "%d", NT);
        "SHIFT": code = $fscanf(fd, "%d", SHIFT);
        "BIAS":  for (k = 0; k < N; k = k + 1) code = $fscanf(fd, "%d", BIAS[k]);
        "A":     for (k = 0; k < TILES*M*K; k = k + 1) code = $fscanf(fd, "%d", A[k]);
        "B":     for (k = 0; k < TILES*K*N; k = k + 1) code = $fscanf(fd, "%d", B[k]);
        "C":     for (k = 0; k < TILES*M*N; k = k + 1) code = $fscanf(fd, "%d", C[k]);
        default: ;
      endcase
    end
    $fclose(fd);
    if (MM != M || KK != K || NN != N || NT != TILES) begin
      $display("MXUACC_XSIM STIMULUS_MISMATCH M=%0d K=%0d N=%0d TILES=%0d", MM, KK, NN, NT);
      $finish;
    end
  end

  // -- the device -------------------------------------------------------------
  reg         a_valid = 0, b_valid = 0, d_valid = 0, req_valid = 0;
  reg         prop = 1;
  reg  [7:0]  tagid = 8'hff;
  reg  signed [7:0] a_bits [0:DIM-1];
  reg  signed [7:0] b_bits [0:DIM-1];
  reg  signed [7:0] d_bits [0:DIM-1];
  reg  [31:0] scale;
  wire a_ready, b_ready, d_ready, req_ready, out_valid;
  wire signed [7:0] out_bits [0:DIM-1];

  MxuAccVpu dut (
    .clock(clk), .reset(rst),
    .io_a_ready(a_ready), .io_a_valid(a_valid),
{chr(10).join(f"    .io_a_bits_{i}_0(a_bits[{i}])," for i in j)}
    .io_b_ready(b_ready), .io_b_valid(b_valid),
{chr(10).join(f"    .io_b_bits_{i}_0(b_bits[{i}])," for i in j)}
    .io_d_ready(d_ready), .io_d_valid(d_valid),
{chr(10).join(f"    .io_d_bits_{i}_0(d_bits[{i}])," for i in j)}
    .io_req_ready(req_ready), .io_req_valid(req_valid),
    .io_req_bits_pe_control_dataflow(1'b1),
    .io_req_bits_pe_control_propagate(prop),
    .io_req_bits_pe_control_shift(5'd0),
    .io_req_bits_a_transpose(1'b0),
    .io_req_bits_bd_transpose(1'b0),
    .io_req_bits_total_rows({rows_w}'d{dim}),
    .io_req_bits_tag_id(tagid),
    .io_req_bits_flush(2'd0),
    .io_scale(scale),
    .io_out_ready(1'b1), .io_out_valid(out_valid),
{chr(10).join(f"    .io_out_bits_data_{i}_0(out_bits[{i}])," for i in j)}
    .io_out_bits_acc_bank_id(), .io_out_bits_fromDMA()
  );

  // -- collecting the rows ----------------------------------------------------
  integer got [0:OUTR-1][0:DIM-1];
  integer rows = 0;
  integer first_in = -1;
  integer last_out = -1;
  integer tile_done [0:TILES-1];
  integer group_done [0:GROUPS-1];
  integer i;

  always @(posedge clk) if (!rst) begin
    if (out_valid) begin
      if (rows < OUTR) for (i = 0; i < DIM; i = i + 1) got[rows][i] = out_bits[i];
      rows = rows + 1;
      last_out = cyc;
      // A group is M rows; a tile is NB groups.
      if (rows % M == 0 && rows / M - 1 < GROUPS) group_done[rows / M - 1] = cyc;
      if (rows % (NB * M) == 0 && rows / (NB * M) - 1 < TILES)
        if (tile_done[rows / (NB * M) - 1] < 0) tile_done[rows / (NB * M) - 1] = cyc;
    end
    if ((a_valid && a_ready) && first_in < 0) first_in = cyc;
  end

  task automatic issue(input integer p, input integer tg);
    integer guard;
    begin
      prop = p; tagid = tg;
      req_valid = 1;
      guard = 0;
      while (req_ready !== 1'b1 && guard < 100) begin @(posedge clk); guard = guard + 1; end
      @(posedge clk);
      req_valid = 0;
    end
  endtask

  // One request: DIM rows. `t, kb, sub` pick the activations (t < 0: none);
  // `bn` the bias columns (< 0: none); `wt, wkb, wnb` the next block's
  // weights, bottom row first (wt < 0: none).
  task automatic pass(input integer t, input integer kb, input integer sub,
                      input integer bn,
                      input integer wt, input integer wkb, input integer wnb);
    integer row, guard, c;
    begin
      row = 0; guard = 0;
      while (row < DIM && guard < 500) begin
        a_valid = 1; b_valid = 1; d_valid = 1;
        for (c = 0; c < DIM; c = c + 1) begin
          a_bits[c] = (t < 0) ? 8'sd0 : A[t*M*K + (sub*DIM + row)*K + kb*DIM + c];
          b_bits[c] = (bn < 0) ? 8'sd0 : BIAS[bn*DIM + c];
          d_bits[c] = (wt < 0) ? 8'sd0 : B[wt*K*N + (wkb*DIM + DIM-1-row)*N + wnb*DIM + c];
        end
        @(posedge clk);
        if (a_ready === 1'b1) row = row + 1;
        guard = guard + 1;
      end
      a_valid = 0; b_valid = 0; d_valid = 0;
    end
  endtask

  // The tag of request (q, sub): bank, add-or-write, last K block, its rows.
  function automatic integer tagof(input integer q, input integer sub);
    integer ft, fnb, fkb;
    begin
      if (q >= TILES * NB * KB) tagof = 8'hff;
      else begin
        ft = q / (NB * KB); fnb = (q / KB) % NB; fkb = q % KB;
        tagof = (sub << 3) | ((fkb == KB-1) << 2) | ((fkb > 0) << 1) | ((ft*NB + fnb) & 1);
      end
    end
  endfunction

  integer t, nb, kb, sub, q, nq, nt, nnb, nkb, r, cidx, wrong, first_bad, gaps, med, tagv;
  integer gap [0:(TILES > GROUPS ? TILES : GROUPS)-1];
  integer tmp;
  initial begin
    for (t = 0; t < TILES; t = t + 1) tile_done[t] = -1;
    for (t = 0; t < GROUPS; t = t + 1) group_done[t] = -1;
    scale = SHIFT;
    repeat (8) @(posedge clk);
    rst = 0;
    @(posedge clk);

    // Warm-up: load block (0, 0, 0)'s weights; its rows are garbage, and its
    // tag is the first real request's.
    issue(1, tagof(0, 0)); pass(-1, 0, 0, -1, 0, 0, 0);
    q = 0;
    for (t = 0; t < TILES; t = t + 1)
      for (nb = 0; nb < NB; nb = nb + 1)
        for (kb = 0; kb < KB; kb = kb + 1) begin
          nq = q + 1;
          nt = nq / (NB * KB); nnb = (nq / KB) % NB; nkb = nq % KB;
          for (sub = 0; sub < SUBS; sub = sub + 1) begin
            tagv = (sub < SUBS-1) ? tagof(q, sub + 1) : tagof(nq, 0);
            issue(sub == 0, tagv);
            pass(t, kb, sub, (kb == 0) ? nb : -1,
                 (sub == SUBS-1 && nt < TILES) ? nt : -1, nkb, nnb);
          end
          q = nq;
        end
    for (t = 0; t < 2000 + 4 * M && rows < OUTR; t = t + 1) @(posedge clk);

    wrong = 0; first_bad = -1;
    for (cidx = 0; cidx < OUTR; cidx = cidx + 1) begin
      t = cidx / (NB * M); nb = (cidx / M) % NB; r = cidx % M;
      for (i = 0; i < DIM; i = i + 1)
        if (cidx >= rows || got[cidx][i] !== C[t*M*N + r*N + nb*DIM + i]) begin
          if (first_bad < 0) first_bad = cidx;
          wrong = wrong + 1;
          i = DIM;
        end
    end

    gaps = 0;
    for (t = 1; t < TILES; t = t + 1)
      if (tile_done[t] > 0 && tile_done[t-1] > 0) begin
        gap[gaps] = tile_done[t] - tile_done[t-1];
        gaps = gaps + 1;
      end
    for (t = 0; t < gaps; t = t + 1)
      for (r = t + 1; r < gaps; r = r + 1)
        if (gap[r] < gap[t]) begin tmp = gap[t]; gap[t] = gap[r]; gap[r] = tmp; end
    med = (gaps > 0) ? gap[gaps/2] : -1;

    $display("MXUACC_STREAM dim=%0d m=%0d k=%0d n=%0d tiles=%0d shift=%0d correct=%s rows_out=%0d want_rows=%0d wrong_rows=%0d first_in=%0d last_out=%0d latency=%0d interval=%0d interval_min=%0d interval_max=%0d total=%0d",
      DIM, M, K, N, TILES, SHIFT,
      (wrong == 0 && rows == OUTR) ? "true" : "false",
      rows, OUTR, wrong, first_in+1, last_out+1,
      (tile_done[0] >= 0 && first_in >= 0) ? tile_done[0] - first_in + 1 : -1,
      med, (gaps > 0) ? gap[0] : -1, (gaps > 0) ? gap[gaps-1] : -1,
      (last_out >= 0 && first_in >= 0) ? last_out - first_in + 1 : -1);
    for (t = 0; t < TILES; t = t + 1)
      $display("MXUACC_TILE t=%0d done=%0d", t, tile_done[t] + 1);
    // The same statistics over groups: one column block's M rows each.
    gaps = 0;
    for (t = 1; t < GROUPS; t = t + 1)
      if (group_done[t] > 0 && group_done[t-1] > 0) begin
        gap[gaps] = group_done[t] - group_done[t-1];
        gaps = gaps + 1;
      end
    for (t = 0; t < gaps; t = t + 1)
      for (r = t + 1; r < gaps; r = r + 1)
        if (gap[r] < gap[t]) begin tmp = gap[t]; gap[t] = gap[r]; gap[r] = tmp; end
    $display("MXUACC_GROUPS groups=%0d first=%0d interval=%0d interval_min=%0d interval_max=%0d",
      GROUPS, (group_done[0] >= 0 && first_in >= 0) ? group_done[0] - first_in + 1 : -1,
      (gaps > 0) ? gap[gaps/2] : -1, (gaps > 0) ? gap[0] : -1, (gaps > 0) ? gap[gaps-1] : -1);
    if (wrong != 0) $display("  first wrong output row: %0d", first_bad);
    $finish;
  end
endmodule
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dim", type=int, required=True, help="the mesh's side")
    parser.add_argument("--stim", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    m, k, n, tiles = shape_of(args.stim)
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write(tb(args.dim, tiles, args.stim, m, k, n))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
