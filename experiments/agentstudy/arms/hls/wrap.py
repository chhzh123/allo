#!/usr/bin/env python3
"""Wrap an exported HLS module as `dut_norm` with the study's port names.

Vitis names a stream port `<name>_dout/_empty_n/_read` for an input and
`<name>_din/_full_n/_write` for an output, and drives reset active low here,
so the wrapper is a rename plus a reset alias. Identical for every trial.
"""
import re, sys

src = open(sys.argv[1], encoding="utf-8", errors="replace").read()
head = src[: src.index(");")] if ");" in src else src
present = set(re.findall(r"\b([abc]_(?:in|out)_\d)_(?:dout|din)\b", head))
rst = "ap_rst_n" if "ap_rst_n" in head else "ap_rst"
ins = [f"a_in_{i}" for i in range(8)] + [f"b_in_{i}" for i in range(8)]
outs = [f"c_out_{i}" for i in range(8)]
missing = [p for p in ins + outs if p not in present]
if missing:
    sys.exit(f"exported module lacks the required ports: {missing[:6]}")

L = ["// generated by the study harness; identical for every trial",
     "`timescale 1ns/1ps", "module dut_norm ("
     , "  input wire ap_clk, input wire ap_rst_n,"]
for p in ins:
    L.append(f"  input wire [7:0] {p}_dout, input wire {p}_empty_n, output wire {p}_read,")
for k, p in enumerate(outs):
    tail = "" if k == len(outs) - 1 else ","
    L.append(f"  output wire [31:0] {p}_din, input wire {p}_full_n, output wire {p}_write{tail}")
L.append(");")
L.append("  gemm_tile u (.ap_clk(ap_clk), " + (".ap_rst_n(ap_rst_n)" if rst == "ap_rst_n" else ".ap_rst(~ap_rst_n)") + ",")
body = []
for p in ins:
    body.append(f"    .{p}_dout({p}_dout), .{p}_empty_n({p}_empty_n), .{p}_read({p}_read)")
for p in outs:
    body.append(f"    .{p}_din({p}_din), .{p}_full_n({p}_full_n), .{p}_write({p}_write)")
L.append(",\n".join(body) + ");")
L.append("endmodule")
print("\n".join(L))
