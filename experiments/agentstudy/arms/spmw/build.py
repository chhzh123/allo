#!/usr/bin/env python3
"""Build and grade one SPMW trial.  usage: build.py <trialdir> <vecset>

The agent writes design.py defining a fabric named `engine`. This stages its
roles, synthesises them, assembles the array, wraps its boundary channels to
the study's port names, and runs the same testbench every arm runs.
"""
import glob
import importlib.util
import os
import shutil
import subprocess
import sys
import time

STUDY = "/scratch/hc676/agentstudy"
ALLO = "/scratch/hc676/allo"
PART = "xcu280-fsvh2892-2L-e"
sys.path.insert(0, os.path.join(ALLO, "scripts"))
sys.path.insert(0, os.path.join(ALLO, "tests", "dataflow", "spmw"))

import allo.spmw as spmw  # noqa: E402
from allo.spmw.rtl import boundary_plan  # noqa: E402
from allo.spmw.shell import families  # noqa: E402
import spmw_build_array as sba  # noqa: E402


def load(path):
    spec = importlib.util.spec_from_file_location("agent_design", path)
    module = importlib.util.module_from_spec(spec)
    sys.modules["agent_design"] = module
    spec.loader.exec_module(module)
    if not hasattr(module, "engine"):
        sys.exit("STUDY BUILD FAIL design.py defines no `engine`")
    return module.engine


def wrapper(graph):
    """`dut_norm`, mapping each boundary channel to its study port.

    A channel's token list says which tensor elements it carries, so the port
    it is follows from the data rather than from any naming convention: an A
    channel carrying row i is `a_in_i`, a B channel carrying column j is
    `b_in_j`, a C channel carrying row i is `c_out_i`.
    """
    plan = boundary_plan(graph)
    fams = {f["name"]: f for f in families(graph)}
    want = {"A": {}, "B": {}, "C": {}}
    for name, fam in fams.items():
        tensor = fam["tensor"]
        if tensor not in want:
            sys.exit(f"STUDY BUILD FAIL wrap: boundary `{name}` carries `{tensor}`, "
                     f"which is not one of A, B, C")
        for index, tokens in enumerate(plan[name]["channels"]):
            rows = sorted({t[0] for t in tokens})
            cols = sorted({t[1] for t in tokens})
            if tensor in ("A", "C"):
                if len(rows) != 1 or len(cols) != 8:
                    sys.exit(f"STUDY BUILD FAIL wrap: `{name}` channel {index} carries "
                             f"{len(tokens)} element(s) of {tensor} spanning rows "
                             f"{rows} and columns {cols}; the task wants 8 channels, "
                             f"channel i carrying row i")
                port = rows[0]
            else:
                if len(cols) != 1 or len(rows) != 8:
                    sys.exit(f"STUDY BUILD FAIL wrap: `{name}` channel {index} carries "
                             f"{len(tokens)} element(s) of B spanning rows {rows} "
                             f"and columns {cols}; the task wants 8 channels, "
                             f"channel j carrying column j")
                port = cols[0]
            order = [t[1] for t in tokens] if tensor in ("A", "C") else [t[0] for t in tokens]
            if order != sorted(order):
                sys.exit(f"STUDY BUILD FAIL wrap: `{name}` channel {index} carries its "
                         f"elements in the order {order}; the task wants ascending")
            want[tensor][port] = (name, index)
    for tensor, label in (("A", "a_in"), ("B", "b_in"), ("C", "c_out")):
        missing = [p for p in range(8) if p not in want[tensor]]
        if missing:
            sys.exit(f"STUDY BUILD FAIL wrap: no boundary channel carries {label}_{missing[0]}")

    lines = ["// generated by the study harness; identical for every trial",
             "`timescale 1ns/1ps", "module dut_norm (",
             "  input wire ap_clk, input wire ap_rst_n,"]
    for i in range(8):
        for pre, w in (("a_in", 7), ("b_in", 7)):
            pass
    for i in range(8):
        lines.append(f"  input wire [7:0] a_in_{i}_dout, input wire a_in_{i}_empty_n, output wire a_in_{i}_read,")
    for i in range(8):
        lines.append(f"  input wire [7:0] b_in_{i}_dout, input wire b_in_{i}_empty_n, output wire b_in_{i}_read,")
    for i in range(8):
        tail = "" if i == 7 else ","
        lines.append(f"  output wire [31:0] c_out_{i}_din, input wire c_out_{i}_full_n, output wire c_out_{i}_write{tail}")
    lines.append(");")

    for name, fam in fams.items():
        n, w = fam["channels"], fam["width"]
        kind = ("dout", "empty_n", "read") if fam["reads"] else ("din", "write", "full_n")
        for suffix, bits in ((kind[0], w), (kind[1], 0), (kind[2], 0)):
            span = f"[{bits - 1}:0] " if bits else ""
            lines.append(f"  wire {span}{name}_{suffix} [0:{n - 1}];")
    for tensor, label in (("A", "a_in"), ("B", "b_in"), ("C", "c_out")):
        for port in range(8):
            name, index = want[tensor][port]
            if tensor == "C":
                lines.append(f"  assign c_out_{port}_din = {name}_din[{index}];")
                lines.append(f"  assign c_out_{port}_write = {name}_write[{index}];")
                lines.append(f"  assign {name}_full_n[{index}] = c_out_{port}_full_n;")
            else:
                lines.append(f"  assign {name}_dout[{index}] = {label}_{port}_dout;")
                lines.append(f"  assign {name}_empty_n[{index}] = {label}_{port}_empty_n;")
                lines.append(f"  assign {label}_{port}_read = {name}_read[{index}];")
    conns = ["    .ap_clk(ap_clk), .ap_rst_n(ap_rst_n)"]
    for name, fam in fams.items():
        kind = ("dout", "empty_n", "read") if fam["reads"] else ("din", "write", "full_n")
        for suffix in kind:
            conns.append(f"    .{name}_{suffix}({name}_{suffix})")
    lines.append("  spmw_top dut (")
    lines.append(",\n".join(conns) + ");")
    lines.append("endmodule")
    return "\n".join(lines) + "\n"


def collect(out, names, sim):
    """The RTL the array needs, the way the array builder collects it."""
    sba._write(os.path.join(out, "genip.tcl"),
               sba.IPGEN_TCL.format(out=out, part=PART, root=out, roles=" ".join(names)))
    sba._run(["vivado", "-mode", "batch", "-source", "genip.tcl", "-nojournal", "-nolog"], out)
    os.makedirs(sim, exist_ok=True)
    sources = ["spmw_fifo.sv", "spmw_const.sv", "spmw_top.sv"]
    for name in sources:
        shutil.copy(os.path.join(out, name), sim)
    for role in names:
        shutil.copy(os.path.join(out, role, f"{role}.sv"), sim)
        sources.append(f"{role}.sv")
        verilog = os.path.join(out, role, "prj", "sol", "syn", "verilog")
        for name in os.listdir(verilog) if os.path.isdir(verilog) else []:
            if name.endswith((".v", ".dat")):
                shutil.copy(os.path.join(verilog, name), sim)
    for root, _dirs, files in os.walk(os.path.join(out, "ipgen")):
        if "sources_1" in root and os.sep + "ip" + os.sep in root + os.sep:
            for name in files:
                if name.endswith(".v"):
                    shutil.copy(os.path.join(root, name), sim)
    return sources


def main():
    trial, vecset = sys.argv[1], (sys.argv[2] if len(sys.argv) > 2 else "visible")
    path = os.path.join(trial, "design.py")
    if not os.path.isfile(path):
        sys.exit("STUDY BUILD no design.py")
    out = os.path.join(trial, "build")
    shutil.rmtree(out, ignore_errors=True)
    os.makedirs(out, exist_ok=True)

    def stage_time(label, fn):
        """Run one stage, time it, and stop at the first one that fails.

        The compiler checks structure before it generates anything, so a design
        with an unbound port or a mismatched link is rejected in seconds. That
        error is worth reporting on its own terms rather than as a traceback
        after a synthesis run that was never going to happen.
        """
        start = time.time()
        try:
            value = fn()
        except FileNotFoundError as exc:
            print("STUDY STAGE %s %.2f" % (label, time.time() - start))
            print("STUDY BUILD ENVIRONMENT %s: %s" % (label, exc))
            sys.stdout.flush()
            sys.exit(2)
        except Exception as exc:  # noqa: BLE001 - the message is the product
            seconds = time.time() - start
            print("STUDY STAGE %s %.2f" % (label, seconds))
            print("STUDY BUILD FAIL %s" % label)
            print("%s: %s" % (type(exc).__name__, exc))
            sys.stdout.flush()
            sys.exit(1)
        print("STUDY STAGE %s %.2f" % (label, time.time() - start))
        return value

    fabric = stage_time("import", lambda: load(path))
    graph = stage_time("elaborate", lambda: spmw.elaborate(fabric))
    names = stage_time("generate", lambda: sba.stage(
        graph, out, PART, 300.0,
        pipeline_style=getattr(fabric, "spmw_pipeline_style", None)))
    stage_time("synthesise", lambda: sba.synthesise(out, names, jobs=8))
    sim = os.path.join(out, "sim")
    sources = stage_time("assemble", lambda: collect(out, names, sim))
    sba._write(os.path.join(sim, "dut_norm.sv"),
               stage_time("wrap", lambda: wrapper(graph)))
    shutil.copy(os.path.join(STUDY, "task", "tb_study.sv"), sim)
    sources += ["dut_norm.sv", "tb_study.sv"]

    import json
    nprod = len(json.load(open(os.path.join(STUDY, "task", "vectors", f"{vecset}.json"))))
    def compile_all():
        sba._run(["xvlog", "-sv"] + sources, sim)
        loose = [f for f in os.listdir(sim) if f.endswith(".v")]
        if loose:
            sba._run(["xvlog"] + loose, sim)

    stage_time("compile", compile_all)
    stage_time("elaborate_rtl", lambda: sba._run(
        ["xelab", "tb", "-s", "tbsim", "--timescale", "1ns/1ps",
         "--generic_top", "NPROD=%d" % nprod, "-L", "unisims_ver",
         "-L", "unimacro_ver", "-L", "secureip"], sim))
    done = stage_time("simulate", lambda: subprocess.run(
        ["xsim", "tbsim", "-runall", "-testplusarg",
         "vecdir=%s/task/vectors/%s" % (STUDY, vecset)],
        cwd=sim, capture_output=True, text=True, check=False))
    shown = 0
    for line in done.stdout.splitlines():
        if "STUDY " in line or "MISMATCH" in line:
            print(line.strip())
            shown += 1
            if shown > 30:
                break
    if "STUDY RESULT" not in done.stdout:
        print("STUDY BUILD FAIL simulation produced no verdict")
        sys.exit(1)


if __name__ == "__main__":
    main()
